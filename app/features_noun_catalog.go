// The Features "By Noun" catalog is pure data, grouped by status: live nouns
// (a registered data.Schema), existing in-app nouns (used today, no schema
// yet) and planned nouns (asked for in the owner's notes and tasks).

// featuresNounCatalog builds the full catalog once. Callers must not mutate
// the returned slice.
var featuresNounCatalog = sync.OnceValue(func() []featuresNounCatalogEntry {
	all := slices.Concat(
		coreFeaturesNounCatalog(),
		newlyLiveFeaturesNounCatalog(),
		existingFeaturesNounCatalog(),
		plannedFeaturesNounCatalog(),
	)
	// Stable, so pr, worktree and tag stay the first planned nouns.
	slices.SortStableFunc(all, func(x, y featuresNounCatalogEntry) int {
		return nounStatusRank(x.Status) - nounStatusRank(y.Status)
	})
	return all
})

var featuresNounCatalogIndex = sync.OnceValue(func() map[string]featuresNounCatalogEntry {
	index := map[string]featuresNounCatalogEntry{}
	for _, entry := range featuresNounCatalog() {
		index[entry.Kind] = entry
	}
	return index
})

func defaultFeaturesNounCatalog() []featuresNounCatalogEntry { return featuresNounCatalog() }

func nounStatusRank(status string) int {
	return slices.Index([]string{NounStatusLive, NounStatusExisting, NounStatusPlanned}, status)
}

// existingNoun describes a concept the app already uses without a registered
// schema; sources are the repo paths it lives in.
func existingNoun(kind, title, icon, summary string, sources, prefixes, keywords []string, verbs ...featuresPlannedVerb) featuresNounCatalogEntry {
	return featuresNounCatalogEntry{
		Kind: kind, Title: title, Icon: icon, Summary: summary, Status: NounStatusExisting,
		Sources: sources, DomainPrefixes: prefixes, Keywords: keywords, PlannedVerbs: verbs,
		Highlights: []string{"Lives in: " + strings.Join(sources, ", "), "In use today without a registered data.Schema"},
	}
}

// plannedNoun describes a noun that is not built yet; sources are the note
// and task refs that ask for it.
func plannedNoun(kind, title, icon, summary string, sources, keywords []string, verbs ...featuresPlannedVerb) featuresNounCatalogEntry {
	return featuresNounCatalogEntry{
		Kind: kind, Title: title, Icon: icon, Summary: summary, Status: NounStatusPlanned, Planned: true,
		Sources: sources, DomainPrefixes: []string{kind + "."}, Keywords: keywords, PlannedVerbs: verbs,
		Highlights: []string{"Requested in: " + strings.Join(sources, ", ")},
	}
}

