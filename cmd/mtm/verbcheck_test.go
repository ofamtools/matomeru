package main

import (
	"testing"

	"ofam.dev/ochazuke/namecheck"
	"ofam.dev/ochazuke/nouncheck"
)

// Every mtm thing noun (a noun with a Store) has the seven core verbs and
// a key prop, and no mtm command noun has a verb named like a core verb
// (Runtime.ValidateNouns). There is no baseline: every noun follows the
// rules, so any new break fails.
func TestNouns(t *testing.T) {
	t.Parallel()
	nouncheck.Check(t, open(t).r, nouncheck.Config{})
}

// Every tracked Go, JSON and Markdown file of mtm (cmd, internal, store,
// docs, README, stories) names only verbs mtm's runtime has, with real
// extension catalogs mounted, or removed ones with their replacement
// (ochazuke's removed_verbs.json). The app's own catalog keeps a noun's
// own motion named move from reading as the purged standard verb.
func TestVerbReferences(t *testing.T) {
	t.Parallel()
	var cat namecheck.Catalog
	for _, a := range vocabApps(t) {
		c := a.r.VerbCatalog()
		if cat.Nouns == nil {
			cat = c
			continue
		}
		for k, v := range c.Nouns {
			cat.Nouns[k] = v
		}
		for k, v := range c.Known {
			if _, ok := cat.Known[k]; !ok || v == "" {
				cat.Known[k] = v
			}
		}
	}
	namecheck.VerbsCheck(t, namecheck.VerbsConfig{
		Catalog: cat,
		Removed: open(t).r.RemovedVerbs(),
		Root:    "../..",
		// Generated reference and build outputs are not sources.
		// The CHANGELOG and release notes are history, generated by
		// o-inventory (mtm does not hand-edit them).
		Skip: []string{"docs/reference/", "bin/", "CHANGELOG.md", "docs/release-notes/"},
		// The fake extensions' own verbs (extensions_test.go,
		// extension_sources_test.go): a tool's verb of its own noun, not
		// the purged thing verbs.
		Allow: []string{"fake.item.rename", "fake.item.move"},
	})
}
